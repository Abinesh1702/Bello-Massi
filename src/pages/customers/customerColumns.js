import { getCreditInfo, getVipStatus, formatAddress } from '../../services/customerService'

/** CSV columns for customer exports (filtered rows). */
export const customerCsvColumns = (lookups) => [
  { header: 'Customer ID', value: (c) => c.id },
  { header: 'Customer Code', value: (c) => c.code },
  { header: 'Customer Name', value: (c) => c.name },
  { header: 'Business Name', value: (c) => c.businessName },
  { header: 'Type', value: (c) => c.type },
  { header: 'Category', value: (c) => c.category },
  { header: 'Status', value: (c) => c.status },
  { header: 'Contact Person', value: (c) => c.contactPerson },
  { header: 'Mobile', value: (c) => c.mobile },
  { header: 'Alternate Mobile', value: (c) => c.altMobile },
  { header: 'Email', value: (c) => c.email },
  { header: 'GSTIN', value: (c) => c.gstNumber },
  { header: 'PAN', value: (c) => c.panNumber },
  { header: 'Address', value: (c) => formatAddress(c) },
  { header: 'City', value: (c) => c.city },
  { header: 'State', value: (c) => c.state },
  { header: 'Pincode', value: (c) => c.pincode },
  { header: 'Assigned Salesman', value: (c) => lookups.people[c.salesRepId]?.name || '' },
  { header: 'Preferred Hub', value: (c) => lookups.hubs[c.hubId]?.name || '' },
  { header: 'Customer Since', value: (c) => c.customerSince },
  { header: 'Credit Enabled', value: (c) => c.creditEnabled },
  { header: 'Credit Limit (INR)', value: (c) => getCreditInfo(c).limit },
  { header: 'Credit Balance (INR)', value: (c) => getCreditInfo(c).balance },
  { header: 'Available Credit (INR)', value: (c) => getCreditInfo(c).available },
  { header: 'Credit Days', value: (c) => c.creditDays },
  { header: 'Credit Status', value: (c) => getCreditInfo(c).status },
  { header: 'VIP', value: (c) => c.isVip },
  { header: 'VIP Pass Number', value: (c) => c.vipPassNumber },
  { header: 'VIP Pass Expiry', value: (c) => c.vipPassExpiry },
  { header: 'VIP Pass Status', value: (c) => getVipStatus(c) },
]
